public class JavaDataType {
    public static void main(String args[]) {
        byte b = 8;
        System.out.println(b);
        // char
        char ch = 'a';
        System.out.println(ch);
        // boolean
        boolean var = false;
        System.out.println(var);
        /*
         * long
         * double
         * float
         * int
         */
        short n = 240;
        System.out.println(n);

        // ADDITION OF TWO NUMBER
        int a = 10;
        int c = 5;
        int sum = a + c;
        System.out.println(sum);
    }
}
