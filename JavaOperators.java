
public class JavaOperators {

    public static void main(String args[]) {
        int A = 10;
        int B = 5;
        // AIRTHMETIC OPERATORS (BINARY)
        System.out.println("add = " + (A + B));
        // (UNARY)
        int C = 24;
        int D = ++C;
        System.out.println(D);

    }
}
